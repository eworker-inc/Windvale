const MAXIMUM_PROJECTS = 8;
const MAXIMUM_NODE_BYTES = 134_217_728;
const MAXIMUM_PHASE_MILLISECONDS = 60_000;
const MAXIMUM_INPUT_BYTES = 536_870_912;
const GENERATOR_MARKER = '// Generated by Tools/Native/Generate-Compiler-Artifact-Readers.mjs.';
export const READINESS_ADVISORY_BYTES = Object.freeze({ Temporary: 2_147_483_648n, Cache: 1_073_741_824n });

function Reject(Message, Exitˉcode = 1) {
    throw Object.assign(new Error(Message), { exitCode: Exitˉcode });
}

export function Requireˉreadinessˉtime(Deadline) {
    if (!Number.isSafeInteger(Deadline) || Date.now() >= Deadline) {
        Reject('Current split-project readiness deadline expired.', 124);
    }
}

function Sameˉpath(Left, Right) {
    return process.platform === 'win32' ? Left.toLowerCase() === Right.toLowerCase() : Left === Right;
}

export function Classifyˉreadinessˉspace(Available, Advisory, Observeˉonly = false) {
    if (typeof Available !== 'bigint' || Available < 0n ||
        typeof Advisory !== 'bigint' || Advisory < 0n || typeof Observeˉonly !== 'boolean') {
        Reject('Invalid readiness filesystem geometry.');
    }
    if (Available === 0n && !Observeˉonly) Reject('The readiness filesystem has no available bytes.');
    return Available < Advisory ? 'Warning' : 'Observed';
}

async function Existingˉdirectory(Candidate, Deadline) {
    const Resolved = path.resolve(Candidate);
    let Existing = Resolved;
    while (true) {
        Requireˉreadinessˉtime(Deadline);
        try { await lstat(Existing); break; }
        catch (Failure) {
            if (Failure.code !== 'ENOENT') throw Failure;
            const Parent = path.dirname(Existing);
            if (Parent === Existing) throw Failure;
            Existing = Parent;
        }
    }
    let Current = path.parse(Existing).root;
    for (const Part of Existing.slice(Current.length).split(path.sep).filter(Boolean)) {
        Current = path.join(Current, Part);
        Requireˉreadinessˉtime(Deadline);
        const Information = await lstat(Current);
        if (!Information.isDirectory() || Information.isSymbolicLink()) {
            Reject(`Readiness path contains a link or non-directory: ${Current}`);
        }
    }
    if (!Sameˉpath(await realpath(Existing), Existing)) Reject(`Readiness path is not canonical: ${Existing}`);
    Requireˉreadinessˉtime(Deadline);
    return { Requested: Resolved, Existing };
}

async function Ordinaryˉfile(Candidate, Maximum, Deadline) {
    Requireˉreadinessˉtime(Deadline);
    const Resolved = path.resolve(Candidate);
    const Information = await lstat(Resolved);
    if (!Information.isFile() || Information.isSymbolicLink() ||
        Information.size < 1 || Information.size > Maximum ||
        !Sameˉpath(await realpath(Resolved), Resolved)) {
        Reject(`Readiness tool/input is not a bounded ordinary file: ${Resolved}`);
    }
    Requireˉreadinessˉtime(Deadline);
    return { Path: Resolved, Information };
}

export function Isˉmaintainedˉartifactˉinput(Repository, Candidate) {
    const Relative = path.relative(path.resolve(Repository), path.resolve(Candidate)).replaceAll('\\', '/');
    return /^Compiler\/Windvale\/[^/]*-Artifact[^/]*\.wv$/u.test(Relative);
}

async function Generatedˉreader(Repository, Candidate, Deadline) {
    if (Isˉmaintainedˉartifactˉinput(Repository, Candidate)) return true;
    if (path.extname(Candidate).toLowerCase() !== '.wv') return false;
    const Before = await Ordinaryˉfile(Candidate, 67_108_864, Deadline);
    const Handle = await open(Before.Path, 'r');
    try {
        const Actual = await Handle.stat();
        if (!Actual.isFile() || Actual.size !== Before.Information.size ||
            Actual.dev !== Before.Information.dev || Actual.ino !== Before.Information.ino) {
            Reject('Readiness input changed before its generated marker was read.');
        }
        const Bufferˉvalue = Buffer.alloc(512);
        const { bytesRead: Bytes } = await Handle.read(Bufferˉvalue, 0, Bufferˉvalue.length, 0);
        Requireˉreadinessˉtime(Deadline);
        return Bufferˉvalue.subarray(0, Bytes).toString('utf8').includes(GENERATOR_MARKER);
    } finally { await Handle.close(); }
}

async function Writableˉprobe(Parent, Deadline) {
    Requireˉreadinessˉtime(Deadline);
    const Probe = path.join(Parent, `.windvale-readiness-${randomBytes(16).toString('hex')}`);
    let Handle = null;
    let Created = false;
    let Primary = null;
    try {
        Handle = await open(Probe, 'wx', 0o600);
        Created = true;
        const Written = await Handle.write(Buffer.from([0]));
        if (Written.bytesWritten !== 1) Reject('Readiness write probe did not write its complete byte.');
        await Handle.close(); Handle = null;
        Requireˉreadinessˉtime(Deadline);
    } catch (Failure) { Primary = Failure; }
    finally {
        try {
            if (Handle !== null) await Handle.close();
            if (Created) await unlink(Probe);
        } catch (Failure) {
            throw Object.assign(new AggregateError(
                Primary === null ? [Failure] : [Primary, Failure],
                'Readiness write-probe cleanup failed.'), { exitCode: 2, cleanupUncertain: true });
        }
    }
    if (Primary !== null) throw Primary;
}

export async function Checkˉprojectˉconstructionˉreadiness(Configuration) {
    const { Repository, Projects, Temporary, Cache, Outputs, Prepare, Preparedˉonly,
        Deadline: Parentˉdeadline } = Configuration;
    Requireˉreadinessˉtime(Parentˉdeadline);
    if (process.arch !== 'x64' || !['win32', 'linux'].includes(process.platform) ||
        typeof Repository !== 'string' || !Array.isArray(Projects) ||
        Projects.length < 1 || Projects.length > MAXIMUM_PROJECTS ||
        !Array.isArray(Outputs) || Outputs.length > MAXIMUM_PROJECTS ||
        typeof Prepare !== 'boolean' || typeof Preparedˉonly !== 'boolean') {
        Reject('Invalid current split-project readiness profile.', 64);
    }
    const Started = Date.now();
    const Deadline = Math.min(Parentˉdeadline, Started + MAXIMUM_PHASE_MILLISECONDS);
    const Node = await Ordinaryˉfile(process.execPath, MAXIMUM_NODE_BYTES, Deadline);
    const Directories = [
        ['Temporary', Temporary, READINESS_ADVISORY_BYTES.Temporary],
        ['Cache', Cache, READINESS_ADVISORY_BYTES.Cache],
        ...Outputs.map(Value => ['Output', path.dirname(Value), 0n]),
    ];
    const Resources = [];
    const Probed = new Set();
    for (const [Role, Candidate, Advisory] of Directories) {
        const Parent = await Existingˉdirectory(Candidate, Deadline);
        const Information = await statfs(Parent.Existing, { bigint: true });
        Requireˉreadinessˉtime(Deadline);
        if (Information.bsize <= 0n || Information.bavail < 0n) Reject('Invalid readiness filesystem geometry.');
        const Available = Information.bsize * Information.bavail;
        const Observeˉonly = Role === 'Cache' && Preparedˉonly;
        const Status = Classifyˉreadinessˉspace(Available, Advisory, Observeˉonly);
        if (Observeˉonly) {
            await access(Parent.Existing, constants.R_OK);
            Requireˉreadinessˉtime(Deadline);
        }
        const Identity = process.platform === 'win32' ? Parent.Existing.toLowerCase() : Parent.Existing;
        if (!Observeˉonly && !Probed.has(Identity)) {
            await Writableˉprobe(Parent.Existing, Deadline);
            Probed.add(Identity);
        }
        Resources.push({ Role, ...Parent, Availableˉbytes: String(Available),
            Advisoryˉbytes: String(Advisory), Status, Access: Observeˉonly ? 'ReadOnlyObservation' : 'WriteProbePassed' });
    }
    const Tooling = path.join(Repository, 'Tools', 'Native');
    const Generator = path.join(Tooling, 'Generate-Compiler-Artifact-Readers.mjs');
    const Context = await Prepareˉnativeˉprojectˉcacheˉcontext('current-split-readiness-v1', [
        path.join(Tooling, 'Project-Construction-Readiness-Core.mjs'), Generator,
    ]);
    Requireˉreadinessˉtime(Deadline);
    const Requests = [];
    const Inputs = new Map();
    let Totalˉbytes = 0;
    let Checkˉgenerator = Prepare;
    for (const Project of Projects) {
        Requireˉreadinessˉtime(Deadline);
        const Request = await Getˉnativeˉprojectˉcacheˉrequest(Context, Project);
        Requireˉreadinessˉtime(Deadline);
        Requests.push(Request);
        for (const Input of Request.inputEvidence) {
            if (Inputs.has(Input.path)) continue;
            Inputs.set(Input.path, Input);
            Totalˉbytes += Input.bytes;
            if (Totalˉbytes > MAXIMUM_INPUT_BYTES) Reject('Readiness closure exceeds 512 MiB.');
            if (!Checkˉgenerator && await Generatedˉreader(Repository, Input.path, Deadline)) Checkˉgenerator = true;
        }
    }
    let Git = null;
    if (Prepare && !Preparedˉonly) {
        Requireˉreadinessˉtime(Deadline);
        const Result = await Runˉdevelopmentˉcommand('git', ['--version'], Deadline, false, 4_096);
        Requireˉreadinessˉtime(Deadline);
        if (Result.Code !== 0 || Result.Error !== '' || !/^git version [^\r\n]{1,128}\r?\n$/u.test(Result.Output)) {
            Reject('Readiness could not identify the Git tool required for preparation.',
                Number.isInteger(Result.Code) && Result.Code >= 1 && Result.Code <= 255 ? Result.Code : 1);
        }
        Git = Result.Output.trim();
    }
    if (Checkˉgenerator) {
        Requireˉreadinessˉtime(Deadline);
        const Result = await Runˉdevelopmentˉcommand(process.execPath, [Generator, '--check'], Deadline, false, 65_536);
        Requireˉreadinessˉtime(Deadline);
        if (Result.Code !== 0 || Result.Error !== '') {
            Reject(`Canonical compiler artifact check failed: ${Result.Error.slice(0, 2_048)}${Result.Output.slice(0, 2_048)}`,
                Number.isInteger(Result.Code) && Result.Code >= 1 && Result.Code <= 255 ? Result.Code : 1);
        }
    }
    for (const Request of Requests) {
        Requireˉreadinessˉtime(Deadline);
        await Requireˉnativeˉprojectˉcacheˉrequestˉunchanged(Request);
        Requireˉreadinessˉtime(Deadline);
    }
    return { Status: 'ReadinessChecked', Host: `${process.platform}-${process.arch}`,
        Node: { Version: process.version, Path: Node.Path, Bytes: Node.Information.size }, Git,
        Projects: Requests.map(Value => ({ Path: Value.projectPath, Inputˉkey: Value.key })),
        Inputˉfiles: Inputs.size, Inputˉbytes: Totalˉbytes, Resources,
        Generator: Checkˉgenerator ? 'CanonicalCheckPassed' : 'NoDeclaredGeneratedReader',
        Elapsedˉmilliseconds: Date.now() - Started, Deadline,
        Compilerˉadmission: 'OrdinaryPathPending', Semanticˉvalidation: 'NotRun' };
}
